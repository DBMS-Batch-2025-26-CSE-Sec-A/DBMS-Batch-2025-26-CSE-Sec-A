SELECT
    NAME,
    TIMESTAMPDIFF(YEAR, BIRTHDAY, CURDATE()) AS AGE,
    MONTHNAME(BIRTHDAY) AS BIRTH_MONTH
FROM
(
    SELECT ROLL, NAME, BIRTHDAY
    FROM Sports_Stud

    UNION

    SELECT ROLL, NAME, BIRTHDAY
    FROM Cultural_Stud
) AS STUDENTS;

