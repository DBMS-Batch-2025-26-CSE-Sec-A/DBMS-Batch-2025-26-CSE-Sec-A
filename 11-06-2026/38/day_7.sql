SELECT CONCAT(CONCAT(FIRST_NAME, ' '), LAST_NAME) AS EMPLOYEE_NAME,
       LENGTH(LAST_NAME) AS NAME_LENGTH,
       INSTR(LAST_NAME, 'a') AS POSITION
FROM EMPLOYEE_DETAILS
WHERE INSTR(JOB_ID, 'CLERK') > 0;


