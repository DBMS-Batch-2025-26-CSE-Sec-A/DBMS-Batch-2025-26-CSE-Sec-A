    ROLL NUMBER(5) PRIMARY KEY,
    NAME VARCHAR2(30) UNIQUE,
    DEPT VARCHAR2(10) CHECK (DEPT IN ('IT', 'CS')),
    SPORTS_FEE NUMBER(8) CHECK (SPORTS_FEE >= 1000)
);

