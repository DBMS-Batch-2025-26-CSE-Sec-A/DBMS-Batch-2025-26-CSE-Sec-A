SELECT LOWER(FIRST_NAME) AS NAME
FROM EMPLOYEE_DETAILS
WHERE DEPARTMENT_ID IN (20,50,80);


SELECT UPPER(LAST_NAME) AS NAME
FROM EMPLOYEE_DETAILS
WHERE DEPARTMENT_ID IN (10,110,60);


SELECT INITCAP(LOWER(JOB_ID)) AS JOB
FROM EMPLOYEE_DETAILS;


SELECT CONCAT(FIRST_NAME,
       CONCAT(' ',LAST_NAME)) AS FULL_NAME
FROM EMPLOYEE_DETAILS;



SELECT LAST_NAME,
       LENGTH(LAST_NAME) AS NAME_LENGTH
FROM EMPLOYEE_DETAILS
WHERE COMMISSION_PCT IS NOT NULL;


SELECT FIRST_NAME || ' ' || LAST_NAME AS FULL_NAME,
       LENGTH(LAST_NAME) AS NAME_LENGTH,
       INSTR(LOWER(LAST_NAME),'a') AS POSITION
FROM EMPLOYEE_DETAILS
WHERE JOB_ID LIKE '%CLERK%';


SELECT LPAD(SALARY,10,'$') AS SALARY
FROM EMPLOYEE_DETAILS;


SELECT TRIM('e' FROM LOWER(FIRST_NAME)) AS TRIMMED
FROM EMPLOYEE_DETAILS
WHERE LOWER(FIRST_NAME) LIKE '%e%';



SELECT DEPARTMENT_ID, SALARY, HIRE_DATE
FROM EMPLOYEE_DETAILS
WHERE LENGTH(FIRST_NAME) = 6;


SELECT FIRST_NAME, JOB_ID,
       INSTR(LOWER(FIRST_NAME),'e') AS POSITION
FROM EMPLOYEE_DETAILS
WHERE LOWER(FIRST_NAME) LIKE '%e%';


SELECT LAST_NAME
FROM EMPLOYEE_DETAILS
WHERE SUBSTR(JOB_ID,4) = 'REP';


SELECT FIRST_NAME, SALARY,
       MOD(SALARY,3000) AS REMAINDER
FROM EMPLOYEE_DETAILS
WHERE JOB_ID = 'SA_REP';



SELECT TO_CHAR(SALARY,'$99,999,999.00') AS SALARY
FROM EMPLOYEE_DETAILS;



SELECT TO_CHAR(SALARY,'$999999') AS SALARY
FROM EMPLOYEE_DETAILS
WHERE DEPARTMENT_ID IN (60,90,110);



SELECT LAST_NAME,
       NVL(TO_CHAR(COMMISSION_PCT),
       'No Commission') AS COMM
FROM EMPLOYEE_DETAILS;



SELECT FIRST_NAME,
       ROUND((SYSDATE-HIRE_DATE)/7,2) AS WEEKS_WORKED
FROM EMPLOYEE_DETAILS;



SELECT FIRST_NAME,
       ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12)
       AS YEARS_WORKED
FROM EMPLOYEE_DETAILS;




SELECT FIRST_NAME,
       ROUND(MONTHS_BETWEEN(SYSDATE,HIRE_DATE),2)
       AS MONTHS_WORKED
FROM EMPLOYEE_DETAILS;


SELECT FIRST_NAME,
       LAST_DAY(HIRE_DATE) AS LAST_DAY
FROM EMPLOYEE_DETAILS;


SELECT FIRST_NAME,
       TO_CHAR(HIRE_DATE,'YEAR') AS HIRE_YEAR
FROM EMPLOYEE_DETAILS;



SELECT ADD_MONTHS(SYSDATE,5) AS "FUTURE DATE"
FROM DUAL;


SELECT FIRST_NAME || ' ' || LAST_NAME AS NAME,
       TO_CHAR(HIRE_DATE,'DAY') AS DAY,
       TO_CHAR(HIRE_DATE,'DD-MON-YYYY') AS JOINING_DATE
FROM EMPLOYEE_DETAILS;



SELECT FIRST_NAME,
       (SALARY * 12) + COMMISSION_PCT AS ANNUAL_SALARY,
       ROUND((SALARY * 12) + COMMISSION_PCT,2)
       AS ROUNDED_SALARY
FROM EMPLOYEE_DETAILS;
