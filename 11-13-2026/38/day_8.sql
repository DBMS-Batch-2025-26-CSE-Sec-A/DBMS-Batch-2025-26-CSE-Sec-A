SELECT NAME,
       TRUNC(MONTHS_BETWEEN(SYSDATE, BIRTHDAY) / 12) AS AGE,
       TO_CHAR(BIRTHDAY, 'FMMonth') AS MONTH_OF_BIRTH
FROM SPORTS_STUD

UNION

SELECT NAME,
       TRUNC(MONTHS_BETWEEN(SYSDATE, BIRTHDAY) / 12) AS AGE,
       TO_CHAR(BIRTHDAY, 'FMMonth') AS MONTH_OF_BIRTH
FROM CULTURAL_STUD

ORDER BY NAME;


