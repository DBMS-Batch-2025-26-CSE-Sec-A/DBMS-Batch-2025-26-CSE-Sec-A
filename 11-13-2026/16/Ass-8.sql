#Q1-A
CREATE TABLE Sports_Stud (
    ROLL INT PRIMARY KEY,
    NAME VARCHAR(30) UNIQUE,
    DEPT VARCHAR(10),
    SPORTS_FEE INT,

    CONSTRAINT chk_sports_dept
    CHECK (DEPT IN ('IT', 'CS')),

    CONSTRAINT chk_sports_fee
    CHECK (SPORTS_FEE >= 1000)
);

